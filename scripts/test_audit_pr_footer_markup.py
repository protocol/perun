#!/usr/bin/env python3
"""audit-pr footer markup: the attribution line a PR body ends with may sit in <sub>, *...* or _..._ and may carry text after
its link, and still ends the last section instead of counting as "Not fixed" detail. Markup does not make a line a footer:
a wrapped line that is not a Generated or Co-Authored-By line, a Generated line with no rule or robot before it, and anything
after a footer are still checked. Fixtures are synthetic (Acme, example.com).
"""
import signal
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_audit_pr_body import FILES, FOOTER, L, drop, sections, with_section  # noqa: E402
from test_audit_pr_footer_rule import BEHAVIOR, COUNTS, detail  # noqa: E402

LINK = "[Claude Code](https://claude.com/claude-code)"
WRAPPED = (f"<sub>🤖 Generated with {LINK}</sub>",
           f"<sup>🤖 Generated with {LINK}</sup>",
           f"*🤖 Generated with {LINK}*",
           f"_🤖 Generated with {LINK}_",
           f"**🤖 Generated with {LINK}**",
           f"🤖 *Generated with {LINK}*",
           f"<sub>🤖 Generated with {LINK} by Jane Smith, reviewed by Acme</sub>")
AFTER_A_RULE = (f"*Generated with {LINK}*",
                f"_Generated by {LINK}_",
                f"<sub>Generated with {LINK}</sub>",
                "<sub>Co-Authored-By: Jane Smith <jane@example.com></sub>",
                "*Co-Authored-By: Jane Smith <jane@example.com>*")


class MarkupStillFooter(unittest.TestCase):
    def test_a_wrapped_robot_line_ends_the_last_section(self):
        for tail in WRAPPED:
            self.assertEqual(detail(f"{COUNTS}\n\n{tail}"), [], tail)
            self.assertEqual(detail(f"{COUNTS}\n\n---\n{tail}"), [], tail)
        self.assertEqual(sections(with_section("Not fixed", f"{COUNTS}\n\n{WRAPPED[0]}"), FILES), [])

    def test_a_wrapped_generated_line_after_a_rule_or_the_robot_line_is_footer_shaped(self):
        for tail in AFTER_A_RULE:
            self.assertEqual(detail(f"{COUNTS}\n\n---\n{tail}"), [], tail)
            self.assertEqual(detail(f"{COUNTS}\n\n{FOOTER}\n{tail}"), [], tail)

    def test_text_after_the_link_is_still_a_footer(self):
        self.assertEqual(detail(f"{COUNTS}\n\n{FOOTER} and Acme's review bot"), [])
        self.assertEqual(detail(f"{COUNTS}\n\n---\nGenerated with {LINK} by Jane Smith"), [])

    def test_the_footer_is_not_content_of_an_empty_last_section(self):
        body = drop(BEHAVIOR) + f"\n## {BEHAVIOR}\n\n{WRAPPED[0]}\n"
        self.assertEqual([p for p in sections(body, FILES) if "is empty" in p], [f"`{BEHAVIOR}` is empty"])


class MarkupHidesNothing(unittest.TestCase):
    def test_a_wrapped_line_that_is_not_a_footer_line_is_content(self):
        for text in ("2 high.\n---\n<sub>see https://example.com/x</sub>",
                     "2 high.\n---\n*src/auth.ts:42*",
                     "2 high.\n---\n_GET /admin/users is open_",
                     "2 high.\n---\n<sub>🤖 src/auth.ts:42</sub>"):
            self.assertEqual(len(detail(text)), 1, text)

    def test_a_generated_line_with_no_rule_or_robot_is_not_a_footer(self):
        for line in (f"*Generated with {LINK}*", f"<sub>Generated with {LINK}</sub>", "_Generated with https://example.com/x_"):
            self.assertEqual(len(detail(f"2 high.\n{line}")), 1, line)

    def test_detail_after_a_wrapped_footer_is_still_checked(self):
        for tail in WRAPPED[:3]:
            got = detail(f"2 high.\n{tail}\nsrc/auth.ts:42")
            self.assertTrue(any("src/auth.ts" in p for p in got), got)


class Bounded(unittest.TestCase):
    @unittest.skipUnless(hasattr(signal, "SIGALRM"), "needs SIGALRM")
    def test_long_runs_of_markup_cannot_hang_the_footer_scan(self):
        def stuck(*_):
            raise AssertionError("the check did not finish in 20 s")

        old = signal.signal(signal.SIGALRM, stuck)
        self.addCleanup(signal.signal, signal.SIGALRM, old)
        self.addCleanup(signal.alarm, 0)
        signal.alarm(20)
        for text in ("*" * 200_000 + "x", "_" * 200_000, "<sub>" * 50_000 + "x", "🤖" + "*" * 200_000 + "x",
                     "🤖 " + "_" * 200_000 + "Generated", ("---\n" + WRAPPED[0] + "\n") * 5_000):
            self.assertIn("not fixed", L._sections(with_section("Not fixed", text)))


if __name__ == "__main__":
    unittest.main()
