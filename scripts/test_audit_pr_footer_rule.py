#!/usr/bin/env python3
"""Tests for the audit-pr footer rule in comms_lint.py: a `---` rule or a `🤖 Generated` line starts a trailing footer
only when everything after it is footer-shaped (blank, `---`, `🤖 Generated ...`, `Generated with/by ...`,
`Co-Authored-By: ...`). Any other text after a rule is still checked, so a rule cannot hide detail in "Not fixed" or
files in "Changes by area". Fixtures are synthetic (Acme, example.com).
"""
import signal
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from test_audit_pr_body import FILES, FOOTER, GOOD, L, drop, sections, with_section  # noqa: E402

TRAILER = "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>"
COUNTS = "2 high, 5 medium findings, tracked privately."
BEHAVIOR = "What changes for reviewers and users"
AREAS = ("- **Export:** require a session. Files: `src/export/handler.ts`.\n\n---\n\n"
         "- **Uploads:** size cap. Files: `src/upload/`, `test/export.test.ts`, `test/upload.test.ts`, `README.md`, `docs/`.\n")


def detail(text):
    """The "Not fixed carries detail" problems for a body whose last section reads `text`."""
    return [p for p in sections(with_section("Not fixed", text), FILES) if "carries detail" in p]


def last_areas(areas):
    """GOOD with "Changes by area" moved to the end and holding `areas`."""
    return drop("Changes by area") + "\n## Changes by area\n" + areas


class DetailAfterARule(unittest.TestCase):
    def test_detail_after_a_rule_in_not_fixed_is_still_checked(self):
        for text in ("2 high.\n\n---\nsrc/auth.ts:42",
                     "2 high.\n---\n\nGET /admin/users is open\n",
                     "2 high.\n---\nsrc/auth.ts:42\n---\n" + FOOTER,
                     "2 high.\n---\nsee https://example.com/x\n" + TRAILER):
            self.assertEqual(len(detail(text)), 1, text)

    def test_detail_after_the_robot_line_is_still_checked(self):
        got = detail(f"2 high.\n{FOOTER}\nsrc/auth.ts:42")
        self.assertTrue(any("src/auth.ts" in p for p in got), got)

    def test_a_robot_line_that_is_not_the_generated_line_is_content(self):
        self.assertEqual(len(detail("2 high.\n---\n🤖 src/auth.ts:42")), 1)

    def test_a_rule_inside_the_last_changes_by_area_hides_nothing(self):
        self.assertEqual(sections(last_areas(AREAS), FILES), [])
        self.assertEqual(sections(last_areas(AREAS) + "\n---\n" + FOOTER, FILES), [])

    def test_a_file_missing_after_a_rule_is_still_reported(self):
        got = sections(last_areas(AREAS.replace("`docs/`", "")), FILES)
        self.assertEqual(len(got), 1, got)
        self.assertIn("1 changed file(s) not named", got[0])
        self.assertIn("docs/guide.md", got[0])

    def test_content_after_a_rule_counts_for_the_last_section(self):
        body = drop(BEHAVIOR) + f"\n## {BEHAVIOR}\n---\n- Uploads over 5 MB return a 413.\n"
        self.assertEqual([p for p in sections(body, FILES) if "is empty" in p], [])


class CompliantFootersStillPass(unittest.TestCase):
    def test_counts_only_with_a_footer_passes(self):
        for tail in (FOOTER,
                     "---\n" + FOOTER,
                     "---\n\n" + FOOTER + "\n\n" + TRAILER,
                     FOOTER + "\n\n" + TRAILER,
                     "---",
                     "---\n---\n" + FOOTER,
                     "  ---  \n  " + FOOTER,
                     "---\n" + TRAILER,
                     "---\nGenerated with [Claude Code](https://claude.com/claude-code)",
                     "---\nGenerated by Claude Code"):
            self.assertEqual(detail(f"{COUNTS}\n\n{tail}"), [], tail)
        self.assertEqual(sections(GOOD + "\n---\n" + FOOTER + "\n" + TRAILER, FILES), [])

    def test_footer_lines_are_not_content_of_an_empty_last_section(self):
        body = drop(BEHAVIOR) + f"\n## {BEHAVIOR}\n\n---\n{FOOTER}\n{TRAILER}\n"
        self.assertEqual([p for p in sections(body, FILES) if "is empty" in p], [f"`{BEHAVIOR}` is empty"])

    def test_a_footer_line_without_a_marker_is_not_a_footer(self):
        self.assertEqual(len(detail("2 high.\nGenerated with https://example.com/x")), 1)


class Bounded(unittest.TestCase):
    @unittest.skipUnless(hasattr(signal, "SIGALRM"), "needs SIGALRM")
    def test_pathological_lines_cannot_hang_the_footer_scan(self):
        def stuck(*_):
            raise AssertionError("the check did not finish in 20 s")

        old = signal.signal(signal.SIGALRM, stuck)
        self.addCleanup(signal.signal, signal.SIGALRM, old)
        self.addCleanup(signal.alarm, 0)
        signal.alarm(20)
        for text in ("---" + " " * 200_000 + "x", "🤖" + " " * 200_000 + "x", "-" * 200_000 + "x", ("---\n" + FOOTER + "\n") * 5_000):
            self.assertIn("not fixed", L._sections(with_section("Not fixed", text)))


if __name__ == "__main__":
    unittest.main()
